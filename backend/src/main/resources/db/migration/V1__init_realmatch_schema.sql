CREATE TABLE user_sanctions (
    sanction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    sanction_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    reason TEXT,
    start_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    end_at TIMESTAMPTZ,
    created_by_admin_id BIGINT REFERENCES admin_users(admin_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_user_sanctions_type CHECK (sanction_type IN ('WARN', 'SUSPEND', 'BAN')),
    CONSTRAINT chk_user_sanctions_status CHECK (status IN ('ACTIVE', 'ENDED'))
);

CREATE TABLE admin_action_logs (
    action_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT REFERENCES admin_users(admin_id) ON DELETE SET NULL,
    target_type VARCHAR(50) NOT NULL,
    target_id BIGINT,
    action_type VARCHAR(50) NOT NULL,
    reason TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_admin_action_logs_action CHECK (action_type IN ('WARN', 'HIDE', 'SUSPEND', 'BAN', 'REFUND_REVIEW', 'RESTORE'))
);

CREATE TABLE content_moderation_logs (
    content_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_type VARCHAR(30) NOT NULL,
    content_id BIGINT NOT NULL,
    action_type VARCHAR(50) NOT NULL,
    admin_id BIGINT REFERENCES admin_users(admin_id) ON DELETE SET NULL,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_content_moderation_logs_content CHECK (content_type IN ('POST', 'COMMENT', 'MESSAGE')),
    CONSTRAINT chk_content_moderation_logs_action CHECK (action_type IN ('HIDE', 'RESTORE', 'DELETE'))
);

CREATE TABLE payment_review_logs (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES payment_orders(payment_id) ON DELETE CASCADE,
    review_type VARCHAR(50) NOT NULL,
    result VARCHAR(50) NOT NULL,
    admin_id BIGINT REFERENCES admin_users(admin_id) ON DELETE SET NULL,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ops_dashboard_snapshots (
    snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metric_code VARCHAR(80) NOT NULL,
    metric_value NUMERIC(20, 4) NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    captured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE service_notices (
    notice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT REFERENCES admin_users(admin_id) ON DELETE SET NULL,
    title VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_service_notices_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'HIDDEN'))
);

CREATE TABLE system_audit_logs (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_type VARCHAR(30) NOT NULL,
    actor_id BIGINT,
    event_type VARCHAR(80) NOT NULL,
    target_type VARCHAR(50),
    target_id BIGINT,
    ip_address INET,
    user_agent TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

