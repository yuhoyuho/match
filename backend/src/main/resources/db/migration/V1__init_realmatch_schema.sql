CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_uuid UUID NOT NULL DEFAULT gen_random_uuid(),
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    nickname VARCHAR(50),
    email VARCHAR(255),
    phone_number VARCHAR(30),
    gender VARCHAR(20),
    birth_year INTEGER,
    is_profile_completed BOOLEAN NOT NULL DEFAULT FALSE,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT ux_users_user_uuid UNIQUE (user_uuid),
    CONSTRAINT chk_users_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'DORMANT', 'WITHDRAWN', 'BANNED')),
    CONSTRAINT chk_users_gender CHECK (gender IS NULL OR gender IN ('MALE', 'FEMALE', 'OTHER', 'UNKNOWN')),
    CONSTRAINT chk_users_birth_year CHECK (birth_year IS NULL OR birth_year BETWEEN 1900 AND 2100)
);

CREATE TABLE user_auth_providers (
    provider_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    provider_type VARCHAR(30) NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    provider_email VARCHAR(255),
    connected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_authenticated_at TIMESTAMPTZ,
    CONSTRAINT ux_auth_provider_identity UNIQUE (provider_type, provider_user_id),
    CONSTRAINT ux_auth_provider_user_type UNIQUE (user_id, provider_type),
    CONSTRAINT chk_auth_provider_type CHECK (provider_type IN ('APPLE', 'GOOGLE', 'KAKAO', 'NAVER'))
);

CREATE TABLE refresh_tokens (
    refresh_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_hash VARCHAR(255) NOT NULL,
    device_id VARCHAR(120),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_refresh_tokens_hash UNIQUE (token_hash)
);

CREATE TABLE user_devices (
    user_device_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    device_id VARCHAR(120) NOT NULL,
    device_os VARCHAR(30) NOT NULL,
    app_version VARCHAR(40),
    push_token VARCHAR(255),
    last_seen_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_user_devices_user_device UNIQUE (user_id, device_id),
    CONSTRAINT chk_user_devices_os CHECK (device_os IN ('IOS', 'ANDROID', 'WEB', 'UNKNOWN'))
);

CREATE TABLE user_terms_agreements (
    agreement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    terms_type VARCHAR(50) NOT NULL,
    terms_version VARCHAR(50) NOT NULL,
    is_agreed BOOLEAN NOT NULL,
    agreed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_user_terms_agreements UNIQUE (user_id, terms_type, terms_version)
);

CREATE TABLE user_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES users(user_id) ON DELETE CASCADE,
    height_cm SMALLINT,
    job_title VARCHAR(100),
    education_level VARCHAR(50),
    mbti VARCHAR(10),
    introduction TEXT,
    region_code VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_user_profiles_height CHECK (height_cm IS NULL OR height_cm BETWEEN 100 AND 250)
);

CREATE TABLE user_profile_images (
    image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    image_url TEXT NOT NULL,
    image_order SMALLINT NOT NULL DEFAULT 0,
    is_main BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_user_profile_images_order UNIQUE (user_id, image_order),
    CONSTRAINT chk_user_profile_images_status CHECK (status IN ('ACTIVE', 'HIDDEN', 'DELETED'))
);

CREATE UNIQUE INDEX ux_user_profile_images_main
    ON user_profile_images(user_id)
    WHERE is_main;

CREATE TABLE user_preferences (
    user_id BIGINT PRIMARY KEY REFERENCES users(user_id) ON DELETE CASCADE,
    preferred_gender VARCHAR(20),
    preferred_age_min SMALLINT,
    preferred_age_max SMALLINT,
    preferred_region_code VARCHAR(50),
    allow_random_call BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_user_preferences_gender CHECK (preferred_gender IS NULL OR preferred_gender IN ('MALE', 'FEMALE', 'ANY')),
    CONSTRAINT chk_user_preferences_age CHECK (
        preferred_age_min IS NULL
        OR preferred_age_max IS NULL
        OR preferred_age_min <= preferred_age_max
    )
);

CREATE TABLE recommendation_exposure_history (
    exposure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    target_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    surface_type VARCHAR(50) NOT NULL DEFAULT 'RECOMMENDATION',
    exposed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_recommendation_exposure_self CHECK (user_id <> target_user_id)
);

CREATE TABLE user_reactions (
    reaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    to_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    reaction_type VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_user_reactions_pair UNIQUE (from_user_id, to_user_id),
    CONSTRAINT chk_user_reactions_type CHECK (reaction_type IN ('LIKE', 'PASS')),
    CONSTRAINT chk_user_reactions_self CHECK (from_user_id <> to_user_id)
);

CREATE TABLE matches (
    match_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user1_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    user2_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    match_source VARCHAR(50) NOT NULL DEFAULT 'RECOMMENDATION',
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    matched_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_matches_pair UNIQUE (user1_id, user2_id),
    CONSTRAINT chk_matches_users CHECK (user1_id < user2_id),
    CONSTRAINT chk_matches_status CHECK (status IN ('ACTIVE', 'ENDED', 'BLOCKED'))
);

CREATE TABLE user_blocks (
    block_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    blocked_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_user_blocks_pair UNIQUE (blocker_id, blocked_user_id),
    CONSTRAINT chk_user_blocks_self CHECK (blocker_id <> blocked_user_id)
);

CREATE TABLE user_reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    target_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    reason TEXT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'RECEIVED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT chk_user_reports_self CHECK (reporter_id <> target_user_id),
    CONSTRAINT chk_user_reports_status CHECK (status IN ('RECEIVED', 'IN_REVIEW', 'RESOLVED', 'REJECTED'))
);

CREATE TABLE activity_log (
    activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    action_type VARCHAR(60) NOT NULL,
    target_type VARCHAR(60),
    target_id BIGINT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE chat_rooms (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
    room_type VARCHAR(30) NOT NULL DEFAULT 'MATCH',
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    CONSTRAINT ux_chat_rooms_match UNIQUE (match_id),
    CONSTRAINT chk_chat_rooms_type CHECK (room_type IN ('MATCH')),
    CONSTRAINT chk_chat_rooms_status CHECK (status IN ('ACTIVE', 'CLOSED', 'BLOCKED'))
);

CREATE TABLE chat_room_members (
    room_id BIGINT NOT NULL REFERENCES chat_rooms(room_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    left_at TIMESTAMPTZ,
    PRIMARY KEY (room_id, user_id)
);

CREATE TABLE chat_messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES chat_rooms(room_id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    message_type VARCHAR(30) NOT NULL DEFAULT 'TEXT',
    content TEXT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'SENT',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delivered_at TIMESTAMPTZ,
    CONSTRAINT chk_chat_messages_type CHECK (message_type IN ('TEXT', 'IMAGE', 'SYSTEM')),
    CONSTRAINT chk_chat_messages_status CHECK (status IN ('SENT', 'DELIVERED', 'READ'))
);

CREATE TABLE chat_read_status (
    room_id BIGINT NOT NULL REFERENCES chat_rooms(room_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    last_read_message_id BIGINT REFERENCES chat_messages(message_id) ON DELETE SET NULL,
    read_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (room_id, user_id)
);

CREATE TABLE chat_message_reports (
    message_report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES chat_messages(message_id) ON DELETE CASCADE,
    reporter_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    reason TEXT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'RECEIVED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT chk_chat_message_reports_status CHECK (status IN ('RECEIVED', 'IN_REVIEW', 'RESOLVED', 'REJECTED'))
);

